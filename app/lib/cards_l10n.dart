class CardText {
  const CardText(this.lang);
  final String lang;

  String t(String key, [Map<String, String> args = const {}]) {
    var text = (lang == 'kk' ? _kk[key] : null) ?? _ru[key] ?? key;
    args.forEach((name, value) => text = text.replaceAll('{$name}', value));
    return text;
  }

  /// Ошибки карт — отсюда, остальные (нет связи, блокировка, лимит частоты) — из общих строк.
  String error(ApiError e) => _ru.containsKey('err.${e.code}') ? t('err.${e.code}') : S(lang).error(e.code, e.detail);
}
