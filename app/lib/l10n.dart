class S {
  const S(this.lang);
  final String lang;

  String t(String key, [Map<String, String> args = const {}]) {
    var text = (lang == 'kk' ? _kk[key] : null) ?? _ru[key] ?? key;
    args.forEach((name, value) => text = text.replaceAll('{$name}', value));
    return text;
  }

  /// «23 ноября, 17:13».
  String date(DateTime at) {
    final months = t('months').split(',');
    String two(int v) => v.toString().padLeft(2, '0');
    return '${at.day} ${months[at.month - 1]}, ${two(at.hour)}:${two(at.minute)}';
  }

  /// Текст ошибки сервера. detail — поля из ответа: retry_after, left, min, attempts_left.
  String error(String code, [Map<String, dynamic> detail = const {}]) {
    final key = 'err.$code';
    if (!_ru.containsKey(key)) return t('err.unknown');
    final args = <String, String>{};
    final wait = detail['retry_after'];
    if (wait is int) {
      args['wait'] = wait < 3600 ? '${(wait / 60).ceil()} ${t('unit.min')}' : '${(wait / 3600).ceil()} ${t('unit.h')}';
    }
    final attempts = detail['attempts_left'];
    if (attempts is int) args['n'] = '$attempts';
    final sum = detail['left'] ?? detail['min'];
    if (sum is int) args['sum'] = money(sum);
    return t(key, args);
  }
}

/// Неразрывный пробел: сумма не разрывается между строками ни между разрядами, ни перед ₸.
const nbsp = '\u00A0';

/// 1250050 тиын → «12 500,50 ₸»; копейки показываются, только если они есть.
String money(int tiyn) {
  final whole = (tiyn.abs() ~/ 100).toString();
  final buf = StringBuffer();
  for (var i = 0; i < whole.length; i++) {
    if (i > 0 && (whole.length - i) % 3 == 0) buf.write(nbsp);
    buf.write(whole[i]);
  }
  final cents = tiyn.abs() % 100;
  final tail = cents == 0 ? '' : ',${cents.toString().padLeft(2, '0')}';
  return '${tiyn < 0 ? '−' : ''}$buf$tail$nbsp₸';
}

/// «+77010000001» → «+7 701 000 00 01».
String phoneText(String phone) {
  final d = phone.replaceAll(RegExp(r'\D'), '');
  if (d.length != 11) return phone;
  return '+${d[0]} ${d.substring(1, 4)} ${d.substring(4, 7)} ${d.substring(7, 9)} ${d.substring(9)}';
}

/// Номер, скрытый до последних двух цифр: «+7 ••• ••• •• 01».
String phoneMasked(String phone) {
  final d = phone.replaceAll(RegExp(r'\D'), '');
  return '+7 ••• ••• •• ${d.length >= 2 ? d.substring(d.length - 2) : '••'}';
}
